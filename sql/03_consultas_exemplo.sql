-- Linhas por tabela
SELECT 'TMC_SETOR' AS tabela, COUNT(*) AS linhas FROM TMC_SETOR
UNION ALL SELECT 'TMC_SERVICO', COUNT(*) FROM TMC_SERVICO
UNION ALL SELECT 'TMC_CALOR_SETOR', COUNT(*) FROM TMC_CALOR_SETOR
UNION ALL SELECT 'TMC_PESSOA_SINTETICA', COUNT(*) FROM TMC_PESSOA_SINTETICA
UNION ALL SELECT 'TMC_LIMIAR_NIVEL_CALOR', COUNT(*) FROM TMC_LIMIAR_NIVEL_CALOR
UNION ALL SELECT 'TMC_LEITURA_CLIMA', COUNT(*) FROM TMC_LEITURA_CLIMA
UNION ALL SELECT 'TMC_RESUMO_DIARIO_CLIMA', COUNT(*) FROM TMC_RESUMO_DIARIO_CLIMA
UNION ALL SELECT 'TMC_NIVEL_CALOR', COUNT(*) FROM TMC_NIVEL_CALOR;

-- ONDE: setores com mais idosos 70+, vulnerabilidade social e nota de calor
-- (ROUND com casas decimais só existe para NUMERIC, daí o ::NUMERIC)
SELECT s.CODIGO, s.POP_70_MAIS, s.IPVS_GRUPO, c.CLASSE_CALOR, ROUND(c.LST_VERAO_C::NUMERIC, 1) AS LST_C
  FROM TMC_SETOR s
  JOIN TMC_CALOR_SETOR c ON c.CODIGO_SETOR = s.CODIGO
 WHERE s.STATUS_CENSO = 'OK'
 ORDER BY c.CLASSE_CALOR DESC, s.IPVS_GRUPO DESC NULLS LAST, s.POP_70_MAIS DESC
 FETCH FIRST 20 ROWS ONLY;

-- QUANDO: nível de calor mais recente, com a leitura do pico e a regra aplicada
-- (no PostgreSQL '-03:00' em AT TIME ZONE seria lido como UTC+3; por isso o nome do fuso)
SELECT n.DATA_LOCAL, n.NIVEL, n.NOME_NIVEL, n.IC_MAX_C,
       l.TEMPERATURA_C, l.UMIDADE_PCT, l.DATA_HORA_UTC AT TIME ZONE 'America/Sao_Paulo' AS HORA_PICO,
       lim.REGRA, lim.ACAO_ESPERADA
  FROM TMC_NIVEL_CALOR n
  JOIN TMC_LEITURA_CLIMA l ON l.ID_LEITURA = n.ID_LEITURA
  LEFT JOIN TMC_LIMIAR_NIVEL_CALOR lim ON lim.ID_LIMIAR = n.ID_LIMIAR
 WHERE n.DATA_LOCAL = (SELECT MAX(DATA_LOCAL) FROM TMC_NIVEL_CALOR);

-- Dias por nível NC
SELECT NIVEL, NOME_NIVEL, COUNT(*) AS DIAS FROM TMC_NIVEL_CALOR GROUP BY NIVEL, NOME_NIVEL ORDER BY NIVEL;
